/**
 * Returns a high-quality Lucide Icon for a given avatar string (emoji or keyword).
 * Falls back to Bot (or specified fallback) if unrecognized.
 */
export function getAgentIcon(
  avatar?: string | null,
  fallback: LucideIcon = Bot
): LucideIcon {
  if (!avatar) return fallback;
  const clean = avatar.trim().toLowerCase();
  if (ICON_MAP[avatar]) return ICON_MAP[avatar];
  if (ICON_MAP[clean]) return ICON_MAP[clean];
  return fallback;
}

