export interface AgentAvatarProps {
  avatar?: string | null;
  className?: string;
  fallbackIcon?: LucideIcon;
}

/**
 * AgentAvatar renders a crisp, high-resolution vector Lucide icon for any agent avatar string.
 * It replaces any legacy emojis with appropriate vector iconography.
 */
export function AgentAvatar({
  avatar,
  className = "w-3.5 h-3.5",
  fallbackIcon = Bot,
}: AgentAvatarProps) {
  const icon = getAgentIcon(avatar, fallbackIcon);
  return React.createElement(icon, { className });
}
